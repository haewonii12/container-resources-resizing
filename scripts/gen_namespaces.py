"""Generate the per-namespace RBAC and the mirror AppProject destinations from deploy/configmap.yaml.

The target namespaces live in the ConfigMap (`namespaces`, `mirror.namespaces`). Kubernetes RBAC cannot follow a
ConfigMap at runtime without granting the agent cluster-wide read, so after changing the list run:

    python scripts/gen_namespaces.py && python scripts/gen_alerts.py

Writes deploy/rbac.yaml, deploy/mirror/rbac.yaml and deploy/report/rbac.yaml, and rewrites only `spec.destinations` of
deploy/mirror/appproject.yaml (its sourceRepos and comments are kept). tests/test_deploy.py checks they are current.
"""

from __future__ import annotations

import io
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from ruamel.yaml import YAML  # noqa: E402

from rightsizing.config import Config  # noqa: E402

DEPLOY = ROOT / "deploy"
HEADER = "# GENERATED by scripts/gen_namespaces.py from deploy/configmap.yaml - do not edit by hand.\n"

READER = """\
apiVersion: rbac.authorization.k8s.io/v1
kind: Role
metadata:
  name: rightsizing-reader
  namespace: {ns}
rules:
  # read-only: there are deliberately NO create/update/patch/delete verbs anywhere (plan Principle 1)
  - apiGroups: [""]
    resources: ["pods", "pods/log", "events", "limitranges"]
    verbs: ["get", "list", "watch"]
  - apiGroups: ["events.k8s.io"]
    resources: ["events"]
    verbs: ["get", "list", "watch"]
  - apiGroups: ["apps"]
    resources: ["deployments", "statefulsets", "replicasets"]
    verbs: ["get", "list", "watch"]
  - apiGroups: ["autoscaling"]
    resources: ["horizontalpodautoscalers"]
    verbs: ["get", "list", "watch"]
  - apiGroups: ["metrics.k8s.io"]
    resources: ["pods"]
    verbs: ["get", "list"]
---
apiVersion: rbac.authorization.k8s.io/v1
kind: RoleBinding
metadata:
  name: rightsizing-reader
  namespace: {ns}
roleRef:
  apiGroup: rbac.authorization.k8s.io
  kind: Role
  name: rightsizing-reader
subjects:
  - kind: ServiceAccount
    name: rightsizing-reader
    namespace: rightsizing
---
"""
READER_ARGO = """\
apiVersion: rbac.authorization.k8s.io/v1
kind: Role
metadata:
  name: rightsizing-app-reader
  namespace: argocd
rules:
  # DV1: read ArgoCD Applications (auto-sync guard, source mapping, sync status)
  - apiGroups: ["argoproj.io"]
    resources: ["applications"]
    verbs: ["get", "list"]
---
apiVersion: rbac.authorization.k8s.io/v1
kind: RoleBinding
metadata:
  name: rightsizing-app-reader
  namespace: argocd
roleRef:
  apiGroup: rbac.authorization.k8s.io
  kind: Role
  name: rightsizing-app-reader
subjects:
  - kind: ServiceAccount
    name: rightsizing-reader
    namespace: rightsizing
"""
MIRROR = """\
apiVersion: rbac.authorization.k8s.io/v1
kind: Role
metadata:
  name: gitops-mirror-reader
  namespace: {ns}
rules:
  # read-only: the mirror never writes workloads
  - apiGroups: ["apps"]
    resources: ["deployments"]
    verbs: ["get", "list"]
  - apiGroups: ["autoscaling"]
    resources: ["horizontalpodautoscalers"]
    verbs: ["get", "list"]
---
apiVersion: rbac.authorization.k8s.io/v1
kind: RoleBinding
metadata:
  name: gitops-mirror-reader
  namespace: {ns}
roleRef: {{apiGroup: rbac.authorization.k8s.io, kind: Role, name: gitops-mirror-reader}}
subjects:
  - {{kind: ServiceAccount, name: gitops-mirror, namespace: rightsizing}}
---
"""
MIRROR_ARGO = """\
apiVersion: rbac.authorization.k8s.io/v1
kind: Role
metadata:
  name: gitops-mirror-apps
  namespace: argocd
rules:
  # create/delete only: no update/patch (cannot enable auto-sync or strip finalizers on existing apps).
  # What a created Application may contain is enforced by the ValidatingAdmissionPolicy + AppProject.
  - apiGroups: ["argoproj.io"]
    resources: ["applications"]
    verbs: ["get", "list", "create", "delete"]
---
apiVersion: rbac.authorization.k8s.io/v1
kind: RoleBinding
metadata:
  name: gitops-mirror-apps
  namespace: argocd
roleRef: {apiGroup: rbac.authorization.k8s.io, kind: Role, name: gitops-mirror-apps}
subjects:
  - {kind: ServiceAccount, name: gitops-mirror, namespace: rightsizing}
"""


REPORT = """\
apiVersion: rbac.authorization.k8s.io/v1
kind: Role
metadata:
  name: daily-report-reader
  namespace: {ns}
rules:
  # read-only: Deployments to report on, plus what the policy needs (HPA, LimitRange)
  - apiGroups: ["apps"]
    resources: ["deployments"]
    verbs: ["get", "list"]
  - apiGroups: ["autoscaling"]
    resources: ["horizontalpodautoscalers"]
    verbs: ["get", "list"]
  - apiGroups: [""]
    resources: ["limitranges"]
    verbs: ["get", "list"]
---
apiVersion: rbac.authorization.k8s.io/v1
kind: RoleBinding
metadata:
  name: daily-report-reader
  namespace: {ns}
roleRef: {{apiGroup: rbac.authorization.k8s.io, kind: Role, name: daily-report-reader}}
subjects:
  - {{kind: ServiceAccount, name: daily-report, namespace: rightsizing}}
"""


def load_config(path: Path = DEPLOY / "configmap.yaml") -> Config:
    """The Config embedded in the ConfigMap (validated: forbidden namespaces and bad names are rejected)."""
    cm = YAML(typ="safe").load(path.read_text(encoding="utf-8"))
    return Config.model_validate(YAML(typ="safe").load(cm["data"]["config.yaml"]) or {})


def _yaml() -> YAML:
    y = YAML()
    y.width = 4096
    y.preserve_quotes = True
    y.indent(mapping=2, sequence=4, offset=2)
    return y


def render(cfg: Config | None = None) -> dict[str, str]:
    cfg = cfg or load_config()
    out = {
        "rbac.yaml": HEADER + "".join(READER.format(ns=ns) for ns in cfg.namespaces) + READER_ARGO,
        "mirror/rbac.yaml": HEADER + "".join(MIRROR.format(ns=ns) for ns in cfg.mirror.namespaces) + MIRROR_ARGO,
        "report/rbac.yaml": HEADER + "---\n".join(REPORT.format(ns=ns) for ns in cfg.namespaces),
    }
    y = _yaml()
    proj = y.load((DEPLOY / "mirror" / "appproject.yaml").read_text(encoding="utf-8"))
    dests = proj["spec"]["destinations"]
    server = dests[0]["server"] if dests else "https://kubernetes.default.svc"
    from ruamel.yaml.comments import CommentedMap, CommentedSeq

    new = CommentedSeq()
    for ns in cfg.mirror.namespaces:
        d = CommentedMap([("server", server), ("namespace", ns)])
        d.fa.set_flow_style()
        new.append(d)
    proj["spec"]["destinations"] = new
    buf = io.StringIO()
    y.dump(proj, buf)
    out["mirror/appproject.yaml"] = buf.getvalue()
    return out


if __name__ == "__main__":
    for name, text in render().items():
        (DEPLOY / name).write_text(text, encoding="utf-8")
        print(f"wrote {DEPLOY / name}")
